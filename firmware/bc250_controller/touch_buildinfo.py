# PlatformIO pre-build step:
#  - rewrites src/buildinfo.cpp with the current time so the build time shown
#    in the UI is the time of this build. (Touching the file is not enough: the
#    build system compares file contents.)
#  - gzips the UI pages (ui/gz/*.gz, embedded through platformio.ini).
#  - turns every translation catalog ui/i18n/<code>.json into byte arrays in
#    src/i18n_data.cpp (docs/TRANSLATING.md). Adding a language needs no change
#    to the build files.
import os, time
Import("env")
path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "buildinfo.cpp")
stamp = time.strftime("%Y-%m-%d %H:%M:%S")
with open(path, "w") as f:
    f.write('// Generated by touch_buildinfo.py on every build. Do not edit.\n'
            '#include "buildinfo.h"\n'
            '#include "version.h"\n'
            'const char *buildTime() { return "%s"; }\n'
            '// Marker the web UI looks for in a firmware file before uploading it,\n'
            '// to show its version and build time: @@BC250FW|version|build time|@@\n'
            'extern const char FW_MARKER[] __attribute__((used)) =\n'
            '    "@@BC250" "FW|" FW_VERSION "|%s|@@";\n'
            'const char *fwMarker() { return FW_MARKER; }\n' % (stamp, stamp))

# The UI pages are embedded gzip-compressed (index.html is about a quarter of
# its size that way): shorter transfers hold the network buffers for a quarter
# of the time. Deterministic output (mtime 0) so unchanged pages do not relink.
import gzip
ui = os.path.join(env.subst("$PROJECT_DIR"), "ui")
os.makedirs(os.path.join(ui, "gz"), exist_ok=True)
for page in ("index.html", "setup.html"):
    with open(os.path.join(ui, page), "rb") as f:
        data = gzip.compress(f.read(), 9, mtime=0)
    out = os.path.join(ui, "gz", page + ".gz")
    if not os.path.exists(out) or open(out, "rb").read() != data:
        with open(out, "wb") as f:
            f.write(data)

# Translation catalogs: minified (untranslated entries left out; of @meta only
# the code and names kept) and gzipped, in a generated source file with the
# table the web server serves from (src/i18n_data.h). The first entry is the
# language list.
import hashlib, json, re
from glob import glob
files = []   # (name, gzip bytes)
langs = []
for path in sorted(glob(os.path.join(ui, "i18n", "*.json"))):
    code = os.path.splitext(os.path.basename(path))[0]
    if code == "en":
        continue   # English is the source text of the UI
    if not re.fullmatch(r"[a-z]{2,3}(-[a-z0-9]{2,8})*", code):
        raise SystemExit("i18n: bad catalog name %s (a lowercase language code, like pl or pt-br)" % path)
    with open(path, encoding="utf-8") as f:
        cat = json.load(f)
    meta = cat.get("@meta") or {}
    if meta.get("code") != code or not meta.get("name"):
        raise SystemExit('i18n: %s needs @meta with "code": "%s" and a "name"' % (path, code))
    out = {}
    for k, v in cat.items():
        if k == "@meta":
            continue
        if isinstance(v, dict):
            v = {f: t for f, t in v.items() if t}
        if v:
            out[k] = v
    raw = json.dumps(out, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    files.append((code, gzip.compress(raw, 9, mtime=0)))
    langs.append({"code": code, "name": meta["name"], "english_name": meta.get("english_name", "")})
raw = json.dumps(langs, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
files.insert(0, ("index", gzip.compress(raw, 9, mtime=0)))
lines = ["// Generated by touch_buildinfo.py from ui/i18n/*.json. Do not edit.",
         '#include "i18n_data.h"', ""]
for i, (name, data) in enumerate(files):
    lines.append("static const uint8_t data%d[] = {" % i)
    for j in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[j:j + 24]) + ",")
    lines.append("};")
lines.append("const I18nFile I18N_FILES[] = {")
for i, (name, data) in enumerate(files):
    lines.append('  {"%s", "\\"%s\\"", data%d, sizeof(data%d)},' % (name, hashlib.sha1(data).hexdigest()[:16], i, i))
lines.append("};")
lines.append("const size_t I18N_FILE_COUNT = %d;" % len(files))
text = "\n".join(lines) + "\n"
out = os.path.join(env.subst("$PROJECT_SRC_DIR"), "i18n_data.cpp")
if not os.path.exists(out) or open(out).read() != text:
    with open(out, "w") as f:
        f.write(text)
